// ── ROUTING ENGINE ────────────────────────────────────────────────────────────

export function routeSchemes(profile) {
  const matches = []
  const {
    socialCategory, familyIncome, projectCost, businessStage,
    sector, artisanTrade, groupType, udyamRegistered,
    dpiitRecognised, foodProcessing, age, startupRecognised, delayedPayment,
  } = profile

  const isSC = socialCategory === 'SC'
  const isST = socialCategory === 'ST'
  const isSCST = isSC || isST
  const incomeBelow5L = familyIncome && Number(familyIncome) <= 500000
  const isArtisan = artisanTrade && artisanTrade !== ''
  const isFoodProcessor = foodProcessing === true || sector === 'food-processing'
  const isStartup = dpiitRecognised || startupRecognised
  const isMSE = udyamRegistered
  const isNewBusiness = businessStage === 'new' || businessStage === 'planning'
  const isExistingBusiness = businessStage === 'existing' || businessStage === 'expansion' || businessStage === 'modernisation'
  const isSHG = groupType === 'SHG'
  const isFPO = groupType === 'FPO'
  const isCooperative = groupType === 'cooperative'
  const isAdult = !age || Number(age) >= 18

  if (isSC && incomeBelow5L && isAdult) {
    const pc = Number(projectCost)
    if (!pc || pc <= 140000) {
      matches.push({ schemeId: 'nsfdc-mfs', matchReasons: ['Scheduled Caste (SC) beneficiary', 'Family income within ₹5 lakh ceiling', 'Project size may fit Micro Finance Scheme'], possibleGaps: ['SC caste certificate required', 'Income proof required', 'Must apply through State Channelising Agency (SCA)', 'SCA will do additional appraisal'], warnings: ['Final approval by SCA/NSFDC. Income must be verified from all sources.'], verificationRequired: true })
    }
    if (pc > 140000 && pc <= 5000000) {
      matches.push({ schemeId: 'nsfdc-term-loan', matchReasons: ['Scheduled Caste (SC) beneficiary', 'Family income within ₹5 lakh ceiling', 'Project size may fit NSFDC Term Loan'], possibleGaps: ['SC caste certificate required', 'Income proof', 'SCA appraisal required', 'Must be a viable income-generating project'], warnings: ['Final approval by SCA. Additional bank/agency conditions may apply.'], verificationRequired: true })
    }
    if (!pc || pc <= 500000) {
      matches.push({ schemeId: 'nsfdc-uny', matchReasons: ['SC beneficiary', 'Family income within ₹5 lakh ceiling', 'UNY suits small/micro income-generating activities'], possibleGaps: ['SC caste certificate required', 'Income proof', 'Channel partner appraisal'], warnings: ['Interest rate is 13%–15% depending on channel.'], verificationRequired: true })
    }
  }

  if (isSCST && (isExistingBusiness || isNewBusiness)) {
    matches.push({ schemeId: 'nssh', matchReasons: [`${socialCategory} beneficiary`, 'National SC-ST Hub provides capital subsidy and market support for SC/ST entrepreneurs'], possibleGaps: ['Enterprise documentation required', 'Udyam/enterprise records needed', 'Activity-specific conditions apply'], warnings: ['Subject to implementing agency conditions. Verify current availability.'], verificationRequired: true })
  }

  if (isArtisan && isAdult) {
    matches.push({ schemeId: 'pm-vishwakarma', matchReasons: ['Engaged in traditional artisan trade', 'PM Vishwakarma covers 18 specified trades', 'Provides toolkit, training and low-interest loans at 5%'], possibleGaps: ['Must be in one of 18 specified trades — verify your trade is covered', 'Identity, household and occupation verification required', 'Outstanding PMEGP/MUDRA loans may affect eligibility'], warnings: ['Only for 18 specified trades. Verify trade coverage at pmvishwakarma.gov.in'], verificationRequired: true })
  }

  if (isNewBusiness && isAdult && !isFoodProcessor) {
    matches.push({ schemeId: 'pmegp-new', matchReasons: ['Starting a new non-farm enterprise', 'PMEGP provides credit-linked subsidy for new micro-enterprises', 'Adults above 18 eligible — no income ceiling'], possibleGaps: ['Project must comply with PMEGP negative list', 'Only one person per family can avail new-unit assistance', 'Bank appraisal required', 'Udyam registration required before physical verification'], warnings: ['Bank must appraise and sanction the loan. Subsidy is margin money — not direct cash.', 'Special categories (SC/ST/OBC/Women etc.) get higher subsidy.'], verificationRequired: true })
  }

  if (isFoodProcessor) {
    if (!isSHG && !isFPO && !isCooperative) {
      matches.push({ schemeId: 'pmfme-individual', matchReasons: ['Food-processing business indicated', 'PMFME Individual component provides 35% capital subsidy up to ₹10 lakh', 'ODOP alignment may strengthen application'], possibleGaps: ['ODOP alignment — verify your district ODOP product', 'Bank loan required for balance', 'FSSAI documentation needed', 'SNA approval required'], warnings: ['Always verify current district ODOP product before applying. Benefits depend on bank loan and project viability.'], verificationRequired: true })
    }
    if (isSHG) {
      matches.push({ schemeId: 'pmfme-shg', matchReasons: ['SHG indicated', 'Food-processing activity', 'PMFME SHG provides ₹40,000 seed capital per member'], possibleGaps: ['SHG registration required', 'Must be food-processing activity', 'SHG federation must be involved'], warnings: [], verificationRequired: true })
    }
    if (isFPO || isCooperative) {
      matches.push({ schemeId: 'pmfme-fpo', matchReasons: ['FPO or cooperative indicated', 'Food-processing value chain activity', 'PMFME FPO/Cooperative provides 35% credit-linked grant'], possibleGaps: ['DPR required', 'Value-chain rationale required', 'SNA approval required'], warnings: [], verificationRequired: true })
    }
  }

  if (isMSE) {
    matches.push({ schemeId: 'cgtmse', matchReasons: ['Udyam-registered MSE', 'CGTMSE provides credit guarantee to reduce collateral burden for MSE loans'], possibleGaps: ['Must use CGTMSE member lending institution', 'Lender does own appraisal'], warnings: ['CGTMSE does NOT pay you directly. It gives the bank a guarantee so you may need less collateral.'], verificationRequired: false })
  }

  if (isMSE && isExistingBusiness) {
    matches.push({ schemeId: 'lean', matchReasons: ['Udyam-registered MSE', 'LEAN provides 90% subsidised lean manufacturing implementation'], possibleGaps: ['Currently focused on manufacturing MSMEs — verify sector eligibility', 'Lean pledge required'], warnings: [], verificationRequired: true })
    if (sector === 'green' || sector === 'manufacturing') {
      matches.push({ schemeId: 'mse-gift', matchReasons: ['Udyam-registered MSE', 'Green/manufacturing sector', 'MSE-GIFT provides 2% interest subvention for green technology'], possibleGaps: ['Must invest in eligible green technology', 'Must use participating FI', 'Sanction window conditions must be met'], warnings: ['Verify current sanction window before applying.'], verificationRequired: true })
    }
  }

  if (isStartup) {
    matches.push({ schemeId: 'sisfs', matchReasons: ['DPIIT startup recognition indicated', 'SISFS provides seed funding up to ₹20 lakh (PoC) and up to ₹50 lakh (scaling)', 'Technology in core offering required'], possibleGaps: ['Incorporation must be within 2 years of application', 'Must apply through eligible incubator', 'Prior govt monetary support must not exceed ₹10 lakh', '51%+ Indian promoter shareholding required'], warnings: ['Grant/debt through incubators — not a direct bank transfer.'], verificationRequired: true })
    matches.push({ schemeId: 'cgss', matchReasons: ['DPIIT-recognised startup', 'CGSS provides credit guarantee for startup loans up to ₹20 crore'], possibleGaps: ['Must not be in NPA/default', 'Lender evaluates viability'], warnings: ['CGSS is a guarantee to the lender — not a direct payment to you.'], verificationRequired: false })
    matches.push({ schemeId: 'sipp', matchReasons: ['DPIIT-recognised startup', 'SIPP facilitates IP protection with government-paid facilitator fees'], possibleGaps: ['Must use empanelled IP facilitators', 'Eligible IP application required'], warnings: [], verificationRequired: false })
  }

  if (delayedPayment) {
    matches.push({ schemeId: 'mse-odr', matchReasons: ['Delayed payment dispute indicated', 'MSE-ODR provides online dispute resolution for delayed payments under MSMED Act'], possibleGaps: ['Must be an MSE (Udyam registered)', 'Must have invoice/contract evidence', 'Must follow ODR portal process'], warnings: ['Outcome depends on dispute facts and MSMED Act applicability.'], verificationRequired: true })
  }

  return matches
}

